(ns kmet.app.composition-gen
  "The composition catalog: the shipped composition written down, generated
   from the same data a boot uses.

   Two sources, both real. Bundles and profiles come from
   `kmet.app.profile` + `kmet.app.catalog` — the described rows `--dump-config`
   prints, minus this machine's user layers. The tool section comes from a
   **minimal boot**: the `:tools` service lists what the model is offered, in
   registration order, so a tool's model-facing text is read rather than copied.

   `docs/composition.md` is this generator's output. Regenerate with
   `bb generate-catalog`; `bb check-catalog` (and `kmet.app.test-catalog`)
   fails when the committed file is stale."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [kmet.app.catalog :as catalog]
            [kmet.app.profile :as profile]
            [kmet.app.registry :as registry]
            [kmet.app.runtime :as runtime]
            [kmet.srce.core :as srce]))

(def doc-path "docs/composition.md")

;; ─── The data ─────────────────────────────────────────────────────────────

(defn rows
  "TABLE's PROFILE-NAME, composed and described through the catalog exactly as
   `compose-config` does it here — no user layers, no `--patch`."
  [table profile-name]
  (:rows (profile/compose (map catalog/describe-layer
                               (profile/layers table profile-name)))))

(defn bundle-rows
  "TABLE's BUNDLE-NAME rows, described."
  [table bundle-name]
  (:rows (catalog/describe-layer (profile/bundle table bundle-name))))

(defn tool-records
  "The model-facing tools a minimal composition mounts, in registry order, as
   the tool maps themselves.
   "
  []
  (let [table (profile/builtin)
        booted (runtime/boot
                (profile/compose
                 [(catalog/describe-layer (profile/bundle table :bundle/minimal))])
                {})]
    (try
      (->> (registry/effective-entries (srce/get (:ctx booted) :tools) :kmet/tool)
           (mapv second))
      (finally (runtime/shutdown! booted)))))

;; ─── Rendering ────────────────────────────────────────────────────────────

(defn- code [v] (str "`" v "`"))

(defn- cell
  "One table cell: no raw pipes or newlines."
  [v]
  (-> (if (nil? v) "" (str v))
      (str/replace "|" "\\|")
      (str/replace #"\s*\n\s*" " ")))

(defn- name-list [names]
  (str/join ", " (map (comp code name) (sort-by name names))))

(def ^:private row-flag-keys
  "The row keys that are not composition data (`kmet.app.profile`), in the
   order the page shows them: the row the entry runs and how, then the rows a
   generic boot or a default selection leaves alone. An explicit false is part
   of the value (an opt-in tool row), so it prints as `key=false`."
  [:mode :prompt :session-lifecycle :defer :default-enabled?])

(defn- row-flags
  "ROW's declared flags, space-separated, or `\"\"`."
  [row]
  (str/join " " (keep (fn [k]
                        (when (contains? row k)
                          (let [v (get row k)]
                            (if (true? v) (name k) (str (name k) "=" v)))))
                      row-flag-keys)))

(defn- row-line [row]
  (str "| " (code (:id row))
       " | " (code (:plugin row))
       " | " (name-list (keys (:inject row)))
       " | " (name-list (:provide row))
       " | " (cell (when-let [c (:config row)] (pr-str c)))
       " | " (row-flags row)
       " |"))

(defn- row-table [rows]
  (str "| row | plugin | injects | provides | config | flags |\n"
       "|---|---|---|---|---|---|\n"
       (str/join "\n" (map row-line rows))
       "\n\n"))

(defn- section [level title body]
  (str (apply str (repeat level "#")) " " title "\n\n" body))

(defn- param-list [{:keys [properties required]}]
  (let [required (set required)]
    (or (str/join ", " (map (fn [[k _]] (str (code k) (when (required k) " (required)")))
                            properties))
        "none")))

(defn- tool-section [{:keys [name label description parameters]}]
  (str "### " (code name) "\n\n"
       "**Label:** " (or label name) "\n\n"
       "**Parameters:** " (param-list parameters) "\n\n"
       "**Description:**\n\n" (str/trimr description) "\n\n"))

(def header
  (str "<!--\n"
       "  Generated by `bb generate-catalog` — do not edit by hand.\n\n"
       "  Bundles and profiles are the built-in composition as a boot sees it\n"
       "  (`kmet.app.profile` + `kmet.app.catalog`); the tool section is a real\n"
       "  minimal boot's `:tools` registry. Change the composition or the row\n"
       "  that declares it, then regenerate. `bb check-catalog` fails when this\n"
       "  file is stale.\n"
       "-->\n\n"
       "# Composition catalog\n\n"
       "The rows a run mounts, as the shipped profiles compose them — no user\n"
       "layers, no `--patch` — and the tools the model is offered. Run\n"
       "`kmet --dump-config` to print the same rows for one machine, including\n"
       "its layers; this page is what the build ships.\n\n"))

(defn markdown
  "The whole catalog document."
  []
  (let [table (profile/builtin)]
    (str header
         (section 2 "Bundles"
                  (apply str
                         (for [name (sort-by str (keys (:bundles table)))]
                           (section 3 (code name)
                                    (row-table (bundle-rows table name))))))
         (section 2 "Profiles"
                  (apply str
                         (for [name (sort-by str (keys (:profiles table)))]
                           (section 3 (code name)
                                    (row-table (rows table name))))))
         (section 2 "Tools"
                  (str "The model-facing surface: each tool the minimal\n"
                       "composition mounts, with the parameters and description the\n"
                       "model reads (`:tools` registration order).\n\n"
                       (str/join "---\n\n" (map tool-section (tool-records))))))))

;; ─── Write and check ──────────────────────────────────────────────────────

(defn write!
  "Write the catalog to DOC-PATH. Returns the path."
  []
  (io/make-parents (io/file doc-path))
  (spit doc-path (markdown))
  doc-path)

(defn check
  "nil when the committed catalog matches the generator, else a sentence naming
   the first difference (what `bb check-catalog` and the test report)."
  []
  (let [f (io/file doc-path)]
    (cond
      (not (.exists f))
      (str doc-path " does not exist — run `bb generate-catalog`")

      :else
      (let [on-disk (slurp f)
            generated (markdown)]
        (when (not= on-disk generated)
          (let [a (str/split-lines on-disk)
                b (str/split-lines generated)
                i (first (keep-indexed (fn [i [x y]] (when (not= x y) i))
                                       (map vector a b)))]
            (if i
              (str doc-path " is stale at line " (inc i)
                   " — run `bb generate-catalog`\n"
                   "  on disk:   " (get a i) "\n"
                   "  generated: " (get b i))
              (str doc-path " is stale: " (count a) " lines on disk, "
                   (count b) " generated — run `bb generate-catalog`"))))))))
